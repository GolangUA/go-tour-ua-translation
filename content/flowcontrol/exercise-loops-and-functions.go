// Sqrt обчислює наближене значення квадратного кореня з x.
// Реалізуйте за методом Ньютона:
//
//	z -= (z*z - x) / (2*z)
//
// Почніть зі значення z := 1.0, виконайте кілька ітерацій і
// зупиніться, коли значення перестане змінюватися (або змінюється дуже мало).
func Sqrt(x float64) float64 {
	// Початкове наближення.
	z := 1.0

	// TODO: Замініть цей фіксований цикл умовою зупинки.
	for i := 0; i < 10; i++ {
		z -= (z*z - x) / (2 * z)
		// TODO: За потреби можна виводити проміжні значення z.
		// fmt.Println(z)
	}

	return z
}

